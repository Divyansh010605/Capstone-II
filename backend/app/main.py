"""
Production FastAPI Application Entrypoint.
AI-Based Stock Market Trend Prediction & Risk Analysis.
Features:
- Full OpenAPI / Swagger UI at /docs
- ReDoc at /redoc
- OpenAPI schema at /openapi.json
- JWT Bearer Authentication & Authorize button
- CORS middleware with regex and explicit origin support
- GZip compression middleware for large data payloads
- Process-Time and standard HTTP security headers middleware
- Health check endpoints
- Modular APIRouters for /api/v1, /api, and root routes
"""

import time
import logging
from contextlib import asynccontextmanager
from fastapi import FastAPI, Request, status
from fastapi.middleware.cors import CORSMiddleware
from fastapi.middleware.gzip import GZipMiddleware
from fastapi.responses import JSONResponse

from backend.app.core.config import settings
from backend.app.core.database import db_manager
from backend.app.api.v1.router import api_router

# Configure root logger
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("stock_market_ai")


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Startup: Connect to MongoDB and initialize indexes
    logger.info("Initializing Stock Market AI Backend Services...")
    await db_manager.connect()
    yield
    # Shutdown: Close database connections
    logger.info("Shutting down Stock Market AI Backend Services...")
    await db_manager.close()


app = FastAPI(
    title="AI-Based Stock Market Trend Prediction & Risk Analysis API",
    description="""
Industry-Level Production API for Stock Market Trend Forecasting, Quantitative Risk Analysis, 
Multi-Asset Virtual Portfolios, and Market Sentiment Analysis.

### Key Capabilities:
- **Market Data Collection**: Real-time quotes, OHLCV candle feeds, and technical indicators (SMA, EMA, RSI, MACD, Bollinger Bands, ATR).
- **AI Trend Predictions**: PyTorch LSTM, GRU, TimeSeriesTransformer, and Calibrated Stacking Ensemble with walk-forward backtest metrics (MAE, RMSE, MAPE, Directional Accuracy).
- **Financial Risk Modeling**: Historical Volatility, Parametric/Historical/Monte Carlo Value at Risk (VaR), Conditional VaR (Expected Shortfall), Maximum Drawdown, Sharpe and Sortino Ratios.
- **Portfolio Management**: Virtual portfolio tracking, P&L, asset allocation, and multi-asset covariance risk.
- **Market Sentiment**: Financial news processing with augmented domain-specific NLP lexicon sentiment scoring.

### Financial Disclaimer:
All forecasts and calculations generated by this platform are experimental statistical models intended strictly for academic and analytical evaluation. **This platform does not provide investment advice or guarantee any trading return.**
    """,
    version="2.0.0",
    docs_url="/docs",
    redoc_url="/redoc",
    openapi_url="/openapi.json",
    lifespan=lifespan,
    swagger_ui_parameters={"persistAuthorization": True},
)

# 1. GZip Compression Middleware (Compresses large historical candle sets)
app.add_middleware(GZipMiddleware, minimum_size=1000)

# 2. Configure CORS
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.BACKEND_CORS_ORIGINS,
    allow_origin_regex=r"^https?://(localhost|127\.0\.0\.1)(:[0-9]+)?$",
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
    expose_headers=["X-Process-Time"],
)


# 3. Process Time & Security Headers Middleware
@app.middleware("http")
async def add_process_time_and_security_headers(request: Request, call_next):
    start_time = time.time()
    response = await call_next(request)
    process_time = time.time() - start_time
    response.headers["X-Process-Time"] = f"{process_time:.4f}s"
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["X-XSS-Protection"] = "1; mode=block"
    response.headers["Referrer-Policy"] = "strict-origin-when-cross-origin"
    return response


# Global Exception Handler
@app.exception_handler(Exception)
async def global_exception_handler(request: Request, exc: Exception):
    logger.error(f"Unhandled exception on {request.method} {request.url.path}: {exc}", exc_info=True)
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content={
            "error": "InternalServerError",
            "message": str(exc),
            "path": request.url.path,
        },
    )


# Health check endpoints
@app.get("/", tags=["Health"])
async def root():
    return {
        "project": settings.PROJECT_NAME,
        "status": "online",
        "version": "2.0.0",
        "documentation": "/docs",
        "redoc": "/redoc",
    }


@app.get("/health", tags=["Health"])
async def health_check():
    return {
        "status": "healthy",
        "database_connected": db_manager.is_connected,
        "services": {
            "ai_engine": "operational",
            "market_data": "operational",
            "risk_calculator": "operational",
            "sentiment_analyzer": "operational",
            "portfolio_manager": "operational",
        },
    }


# Include Routers under /api/v1, /api, and root /
app.include_router(api_router, prefix=settings.API_V1_STR)
app.include_router(api_router, prefix="/api")
app.include_router(api_router)


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(
        "backend.app.main:app",
        host=settings.BACKEND_HOST,
        port=settings.BACKEND_PORT,
        reload=settings.DEBUG,
    )
